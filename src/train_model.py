    "\n",
    "def train():\n",
    "    # Load features\n",
    "    df = pd.read_csv(IN, low_memory=False)\n",
    "    print(\"Loaded features shape:\", df.shape)\n",
    "\n",
    "    # Define target and X\n",
    "    target = \"price\"\n",
    "    if target not in df.columns:\n",
    "        raise ValueError(\"Target column 'price' not found in features CSV.\")\n",
    "\n",
    "    X = df.drop(columns=[target]).copy()\n",
    "    y = df[target].values\n",
    "\n",
    "    # Convert all feature cols to numeric (non-numeric -> NaN)\n",
    "    X = X.apply(pd.to_numeric, errors='coerce')\n",
    "\n",
    "    # Show which columns have NaNs and how many (for debugging)\n",
    "    nan_counts = X.isna().sum()\n",
    "    nan_cols = nan_counts[nan_counts > 0].sort_values(ascending=False)\n",
    "    if not nan_cols.empty:\n",
    "        print(\"Columns with missing values (pre-imputation):\")\n",
    "        print(nan_cols)\n",
    "    else:\n",
    "        print(\"No missing values found in features (pre-imputation).\")\n",
    "\n",
    "    # Impute numeric NaNs with median (Ridge requires no NaNs)\n",
    "    imputer = SimpleImputer(strategy=\"median\")\n",
    "    X_imputed_arr = imputer.fit_transform(X)  # returns numpy array\n",
    "    X_imputed = pd.DataFrame(X_imputed_arr, columns=X.columns, index=X.index)\n",
    "\n",
    "    # Sanity check: any remaining NaNs?\n",
    "    if X_imputed.isna().sum().sum() > 0:\n",
    "        raise RuntimeError(\"Imputation failed — NaNs remain in X_imputed.\")\n",
    "\n",
    "    # Simple train-test split\n",
    "    X_train, X_test, y_train, y_test = train_test_split(X_imputed, y, test_size=0.15, random_state=42)\n",
    "    print(\"Train shape:\", X_train.shape, \"Test shape:\", X_test.shape)\n",
    "\n",
    "    # Baseline: Ridge regression\n",
    "    ridge = Ridge(alpha=1.0, random_state=42)\n",
    "    ridge.fit(X_train, y_train)\n",
    "    y_pred_ridge = ridge.predict(X_test)\n",
    "    ridge_mae = mean_absolute_error(y_test, y_pred_ridge)\n",
    "    ridge_rmse = np.sqrt(mean_squared_error(y_test, y_pred_ridge))\n",
    "    print(f\"Ridge MAE: {ridge_mae:.4f}  RMSE: {ridge_rmse:.4f}\")\n",
    "    os.makedirs(os.path.dirname(BASELINE_OUT), exist_ok=True)\n",
