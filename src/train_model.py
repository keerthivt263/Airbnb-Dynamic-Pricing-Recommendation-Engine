    "\n",
    "    params = {\n",
    "        \"objective\": \"regression\",\n",
    "        \"metric\": \"rmse\",\n",
    "        \"verbosity\": -1,\n",
    "        \"boosting_type\": \"gbdt\",\n",
    "        \"learning_rate\": 0.05,\n",
    "        \"num_leaves\": 31,\n",
    "        \"seed\": 42\n",
    "    }\n",
    "\n",
    "    # Train with early stopping\n",
    "    from lightgbm import early_stopping, log_evaluation\n",
    "\n",
    "# Train with early stopping (new LightGBM API)\n",
    "    gbm = lgb.train(\n",
    "        params,\n",
    "        lgb_train,\n",
    "        num_boost_round=2000,\n",
    "        valid_sets=[lgb_train, lgb_val],\n",
    "        callbacks=[\n",
    "            early_stopping(stopping_rounds=50),\n",
    "            log_evaluation(100)\n",
    "        ]\n",
    "    )\n",
    "\n",
    "    # Evaluate\n",
    "    y_pred_gbm = gbm.predict(X_test, num_iteration=gbm.best_iteration)\n",
    "    gbm_mae = mean_absolute_error(y_test, y_pred_gbm)\n",
    "    gbm_rmse = np.sqrt(mean_squared_error(y_test, y_pred_gbm))\n",
    "    print(f\"LightGBM MAE: {gbm_mae:.4f}  RMSE: {gbm_rmse:.4f}\")\n",
    "\n",
    "    os.makedirs(os.path.dirname(MODEL_OUT), exist_ok=True)\n",
    "    joblib.dump(gbm, MODEL_OUT)\n",
    "    print(f\"Saved LightGBM model to {MODEL_OUT}\")\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    train()\n"
